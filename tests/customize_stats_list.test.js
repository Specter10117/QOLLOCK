"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const load = require("./load_settings_environment");

test("native Stats List has independent draft geometry, history, reset and settings exchange", () => {
    const e = load(), g = e.global, Q = g.QOL;
    Q.ui.window.setOpen(true); e.clock.advance(500);
    const add = (parent, id, classes = []) => parent.addChild(e.doc.create("Panel", { id, classes }));
    const core = add(e.hud.root, "", ["HudCore"]);
    const active = add(core, "hudActivePlayerStats");
    const compact = add(active, "HudStatBlock");
    const list = add(active, "StatList");
    Object.assign(compact, { actuallayoutwidth: 270, actuallayoutheight: 80 });
    Object.assign(list, { actuallayoutwidth: 320, actuallayoutheight: 600 });
    list.style.transform = "rotateZ(2deg)";
    const find = id => e.em.FindChildTraverse(id);
    const element = Q.presentation.elements.find(item => item.id === "statsList");
    assert.ok(element, "native StatList is a separate customization surface");
    assert.equal(Q.ui.customize.start(null, { elementId: "playerStats" }), true);
    assert.ok(find("QOLCustomizeSelect_statsList"));
    find("QOLCustomizeSelect_statsList")._fire("onactivate");
    const edit = (suffix, value) => {
        const input = find("QOLCustomize_STATS_LIST_" + suffix);
        assert.ok(input); input.text = String(value); input._fire("oninputsubmit");
    };
    edit("X_OFFSET", 83); edit("Y_OFFSET", -42); edit("SCALE", 135); edit("OPACITY", 47);
    e.clock.advance(1200);
    assert.equal(list.style.x, "83px"); assert.equal(list.style.y, "42px");
    assert.equal(list.style.uiScale, "135%"); assert.equal(list.style.opacity, "0.47");
    assert.equal(compact.style.uiScale, undefined); assert.equal(active.style.x, undefined);
    assert.equal(g.MOD_CONFIG.STATS_LIST_SCALE, 100, "draft never mutates canonical config");
    find("QOLCustomizeReset")._fire("onactivate"); e.clock.advance(1200);
    assert.equal(list.style.x, undefined); assert.equal(list.style.uiScale, undefined);
    find("QOLCustomizeUndo")._fire("onactivate"); e.clock.advance(1200);
    assert.equal(list.style.x, "83px"); assert.equal(list.style.uiScale, "135%");
    find("QOLCustomizeCancel")._fire("onactivate"); e.clock.advance(1200);
    assert.equal(list.style.x, undefined); assert.equal(list.style.opacity, undefined);
    assert.equal(list.style.transform, "rotateZ(2deg)");
    Q.ui.customize.start(null, { elementId: "statsList" });
    edit("X_OFFSET", 83); edit("Y_OFFSET", -42); edit("SCALE", 135); edit("OPACITY", 47);
    find("QOLCustomizeApply")._fire("onactivate"); e.clock.advance(1200);
    const imported = Q.ui.modal.tryApplyImportStringWithDiagnostics(Q.ui.configTab.getCurrentExportSettingsString());
    assert.equal(imported.ok, true); assert.equal(imported.candidateConfig.STATS_LIST_X_OFFSET, 83);
    assert.equal(imported.candidateConfig.STATS_LIST_SCALE, 135);
    assert.equal(imported.candidateConfig.STATS_LIST_Y_OFFSET, -42);
    assert.equal(imported.candidateConfig.STATS_LIST_OPACITY, 0.47);
    const retired = add(e.hud.root, "RetiredList"); list.SetParent(retired);
    const replacement = add(active, "StatList"); e.clock.advance(1200);
    assert.equal(list.style.x, undefined); assert.equal(list.style.uiScale, undefined);
    assert.equal(replacement.style.x, "83px"); assert.equal(replacement.style.uiScale, "135%");
    assert.equal(replacement.style.y, "42px"); assert.equal(replacement.style.opacity, "0.47");
    e.hud.sandbox.global.QOL.core.FeatureRegistry.disable("ql_presentation_scale");
    assert.equal(replacement.style.x, undefined); assert.equal(replacement.style.uiScale, undefined);
    assert.deepEqual(e.clock.errors, []); assert.deepEqual(e.doc.eventErrors, []);
});
